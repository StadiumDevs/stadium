// Converts the project feedback markdown (the versioned source of truth, e.g.
// server/fixtures/free-society-hack-2026/project-feedback/v1.0.1.md) into the
// JSON fixture Stadium reads (v1.0.1.json next to it).
//
//   node scripts/convert-project-feedback.js fixtures/free-society-hack-2026/project-feedback/v1.0.1.md
//
// Pure: no database. Fails loudly on a section it doesn't understand. Judge
// counts ("Judges: 3/6") and the per-section score line are not carried over:
// the page shows scores from the API and no judge counts.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const strip = (s) => s.replace(/\*\*/g, '').trim();
const EMAIL = /[\w.+-]+@[\w-]+\.[\w.]+/;

function versionTable(lines) {
  const out = {};
  for (const l of lines) {
    if (!l.startsWith('|')) continue;
    const cells = l.replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
    if (cells.length >= 2 && cells[0] && !/^-+$/.test(cells[0])) out[cells[0]] = strip(cells[1]).replace(/`/g, '');
  }
  return out;
}

/** The bullets under a bold heading ("**What worked**") inside one section, or []. */
function bullets(block, heading) {
  const i = block.indexOf(`**${heading}**`);
  if (i < 0) return [];
  const out = [];
  for (const l of block.slice(i).split('\n').slice(1)) {
    if (l.startsWith('- ')) out.push(l.slice(2).trim());
    else if (l.trim() === '') {
      if (out.length) break;
    } else break;
  }
  return out;
}

function parseSection(raw) {
  const [titleLine, ...rest] = raw.split('\n');
  const title = titleLine.trim();
  const body = rest.join('\n');
  const paras = body.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean);
  const meta = paras[0];
  if (!meta || !/Basis: /.test(meta)) throw new Error(`${title}: no "… · Basis: …" line`);
  const fields = meta.split(' · ').map((f) => f.trim());
  const field = (name) => fields.find((f) => f.startsWith(`${name}:`))?.slice(name.length + 1).trim() ?? null;
  const repo = field('Repo');
  const basisRaw = field('Basis');
  const basis = /notes/.test(basisRaw ?? '') ? 'scores and judges’ notes' : 'scores only';
  const scoresIdx = paras.findIndex((p) => p.startsWith('Scores (normalized)'));
  const summary = paras.find((p, i) => i > Math.max(0, scoresIdx) && !p.startsWith('**') && !p.startsWith('- '));
  if (!summary) throw new Error(`${title}: no summary paragraph`);
  const worked = bullets(body, 'What worked');
  const improve = bullets(body, 'What to improve');
  if (!improve.length) throw new Error(`${title}: no "What to improve" items`);
  const facts = bullets(body, 'Checked facts').map((f) => {
    const m = f.match(/^(.*?)\s*\*Source:\s*(.*?)\*\s*$/);
    return m ? { text: m[1].trim(), source: m[2].replace(/\.$/, '').trim() } : { text: f, source: null };
  });
  return {
    title,
    repo: repo && /^https?:\/\//.test(repo) ? repo : null,
    prize: field('Prize'),
    ecosystemPrize: fields.includes('Ecosystem Prize'),
    basis,
    summary: summary.replace(/\s*\n\s*/g, ' '),
    worked,
    improve,
    facts,
  };
}

export function convertProjectFeedback(md, { expectedProjects = 48 } = {}) {
  const text = md.replace(/\r\n/g, '\n');
  const lines = text.split('\n');
  const meta = versionTable(lines.slice(0, lines.findIndex((l) => l.startsWith('**Changelog**'))));
  for (const k of ['Version', 'Generated', 'Generated by']) if (!meta[k]) throw new Error(`Version table has no "${k}" row`);
  const changelog = [];
  for (let i = lines.findIndex((l) => l.startsWith('**Changelog**')) + 1; i < lines.length && lines[i].startsWith('- '); i += 1) {
    const m = lines[i].match(/^- ([\d.]+) \(([^)]+)\):\s*(.*)$/);
    if (!m) throw new Error(`Changelog line not understood: "${lines[i]}"`);
    changelog.push({ version: m[1], date: m[2], text: m[3] });
  }
  const section = (h) => {
    const i = text.indexOf(`\n## ${h}\n`);
    if (i < 0) return '';
    const after = text.slice(i + h.length + 5);
    const j = after.indexOf('\n## ');
    return j < 0 ? after : after.slice(0, j);
  };
  const method = section('Method')
    .split('\n')
    .filter((l) => l.startsWith('- '))
    .map((l) => l.slice(2).trim());
  const feedback = section('Feedback');
  const projects = feedback.split(/\n### /).slice(1).map(parseSection);
  if (projects.length !== expectedProjects) throw new Error(`Expected ${expectedProjects} projects, found ${projects.length}`);
  const titles = new Set(projects.map((p) => p.title));
  if (titles.size !== projects.length) throw new Error('Duplicate project titles');
  const json = JSON.stringify(projects);
  if (EMAIL.test(json)) throw new Error('An email address is in the feedback text');
  if (/\bJudge [A-Z]\b|Judges: \d/.test(json)) throw new Error('A named judge or a judge count is in the feedback text');
  return {
    version: {
      version: meta.Version,
      generated: meta.Generated,
      generatedDate: meta.Generated.split(',')[0].trim(),
      generatedBy: meta['Generated by'],
      scores: meta.Scores ?? null,
      notes: meta["Judges' notes"] ?? null,
      factCheck: meta['Fact check'] ?? null,
      changelog,
    },
    method,
    projects,
  };
}

/** The JSON text written next to the markdown (stable, so a test can compare it). */
export const projectFeedbackJson = (md) => `${JSON.stringify(convertProjectFeedback(md), null, 2)}\n`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const input = process.argv[2];
  if (!input || !input.endsWith('.md')) {
    console.error('Usage: node scripts/convert-project-feedback.js <dir>/v<version>.md');
    process.exit(1);
  }
  const out = input.replace(/\.md$/, '.json');
  try {
    fs.writeFileSync(out, projectFeedbackJson(fs.readFileSync(input, 'utf8')));
    console.log(`Wrote ${out}`);
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
